/**
 * Заставка при запуске (1.0, этап 1.2): владелец 2026-11-01 попросил держать заставку не меньше 2,4 с — её не успевали увидеть;
 * ТЗ 1.0 — повторный запуск не дольше 1,5 с. Правило: минимум — только при первом запуске за день, повторные в тот же день — без паузы.
 */
import { describe, expect, it } from 'vitest';
import { splashMinMs } from '../src/launch';

describe('минимальный показ заставки', () => {
  it('первый запуск (заставку ещё не показывали) — полный минимум', () => {
    expect(splashMinMs(null, '2026-11-28', 2400)).toBe(2400);
  });
  it('первый запуск нового дня — полный минимум', () => {
    expect(splashMinMs('2026-11-27', '2026-11-28', 2400)).toBe(2400);
  });
  it('повторный запуск в тот же день — без искусственной паузы', () => {
    expect(splashMinMs('2026-11-28', '2026-11-28', 2400)).toBe(0);
  });
  it('мусор в хранилище — как первый запуск', () => {
    expect(splashMinMs('not-a-day', '2026-11-28', 2400)).toBe(2400);
  });
});
